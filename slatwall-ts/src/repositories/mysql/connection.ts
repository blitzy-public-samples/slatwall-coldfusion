/**
 * One row of a result set, keyed by column name.
 *
 * JUDGMENT CALL: values are `unknown`, and this type is deliberately not generic. Both halves of
 * that are load-bearing.
 *
 * The driver's own row type, `RowDataPacket`, declares `[column: string]: any`.
 */
export type SqlRow = Readonly<Record<string, unknown>>;

/**
 * A value that may be bound to a `?` placeholder.
 *
 * The union mirrors the driver's own bindable space, minus the shapes that are always a mistake
 * here (see `isSqlParameter`).
 *
 * CFML parity [model/dao/PriceGroupDAO.cfc:L65]: a legacy `<cfqueryparam>` declared a `cfsqltype`
 * and the engine checked the value against it. Binding through this union, checked at the
 * boundary, is that guarantee carried forward.
 */
export type SqlParameter = string | number | bigint | boolean | Date | Buffer | null;

/**
 * What a data-modifying statement reports back.
 *
 * JUDGMENT CALL: `insertId` is deliberately absent. Every in-scope entity declares
 * `fieldtype="id" generator="uuid"`, so a primary key is generated by the application and written
 * as a `varchar`, never by `AUTO_INCREMENT`.
 */
export interface SqlMutationResult {
  /**
   * Rows the statement affected. This is what a delete or update reports on.
   */
  readonly affectedRows: number;
  /**
   * Server warning count for the statement. Non-zero deserves investigation.
   */
  readonly warningStatus: number;
}

/**
 * WHO is making a write, as the write boundary is permitted to know it.
 *
 * Each is guarded by
 * `!getHibachiScope().getAccount().isNew() && getHibachiScope().getAccount().getAdminAccountFlag()`
 * note that `isNew()` is the ACCOUNT's, not the entity's - and both blocks sit inside an
 * `hasApplicationValue("initialized")` gate `model/dao/PromotionDAO.cfc`,
 * `model/dao/PromotionDAO.cfc`.
 */
export interface AuditActorContext {
  /**
   * The authenticated account, as an opaque identifier.
   *
   * ABSENT MEANS no PERSISTED ACCOUNT, which is the target's representation of the legacy
   * `getAccount().isNew()` half of the gate: the CFML scope hands back a new, empty account object
   * when nobody is signed in.
   */
  readonly accountID?: string | undefined;

  /**
   * Whether that account carries the legacy admin flag.
   */
  readonly adminAccountFlag: boolean;
}

/**
 * An actor context that stamps nothing - the shape a non-admin or anonymous request has, and the
 * safe default.
 */
export const UNATTRIBUTED_AUDIT_ACTOR: AuditActorContext = Object.freeze({
  adminAccountFlag: false,
});

/**
 * The account identifier a write may stamp, or `undefined` when the legacy gate refuses.
 *
 * Evaluated here alone, so the four repositories cannot drift apart on it: an INSERT reads
 * `undefined` as "stamp no actor", and an UPDATE renders it through
 * {@link sqlUpdateAssignment} so a stored actor is never overwritten with null.
 *
 * @param actor the request's audit actor.
 * @returns the account identifier to stamp, or `undefined` when the gate refuses.
 */
export function resolveAuditActorAccountID(actor: AuditActorContext): string | undefined {
  if (!actor.adminAccountFlag) {
    return undefined;
  }

  const accountID = actor.accountID;
  if (accountID === undefined || accountID.length === 0) {
    return undefined;
  }

  return accountID;
}

/**
 * The columns whose UPDATE assignment must never overwrite a stored value with null.
 *
 * Exported so a test can name them without restating the literals, and so the helpers below cannot
 * disagree about which columns are special.
 */
export const AUDIT_ACTOR_COLUMNS: readonly string[] = Object.freeze([
  'createdByAccountID',
  'modifiedByAccountID',
]);

/**
 * Render one `SET` assignment for an UPDATE statement.
 *
 * Every column renders as `name = ?` - EXCEPT the two audit account columns, which render as
 * `name = COALESCE(?, name)`.
 *
 * THE SECOND PARAMETER GENERALISES THE SAME MECHANISM TO A CALLER-NAMED COLUMN, AND IT EXISTS
 * BECAUSE A WHOLE-ROW UPDATE CAN ERASE A KEY IT WAS NEVER TOLD ABOUT. Repricing through
 * `processProduct_updateSkus` wrote `SwSku.productID` as SQL NULL at HTTP 200, orphaning every SKU
 * the request touched. The cause is
 * structurally identical to the audit-actor case this helper already existed for: the
 * statement bound a column the ENTITY COULD NOT REPORT. A SKU reached through the inverse
 * side of its own association - `Product.skus` - carries no back-reference to its owner, so
 * `sku.getProduct()` answered nothing and the whole-row UPDATE dutifully wrote that nothing
 * over a stored foreign key.
 *
 * Hibernate never had that failure mode, and the reason is worth stating precisely: it
 * flushed the DIRTY COLUMNS of a managed entity, and an association that was never
 * initialised is not dirty, so no assignment for it was emitted at all. A hand-built
 * whole-row UPDATE has no dirty-column knowledge to draw on. `COALESCE(?, column)` is the
 * SQL expression of the same rule: bind the value when the entity can report one, and leave
 * the stored value standing when it cannot.
 *
 * ⚠ WHAT THE CALLER IS ASSERTING BY NAMING A COLUMN HERE, stated plainly so the affordance is
 * not used casually. A column rendered this way CANNOT BE SET TO NULL BY THAT STATEMENT.
 * Naming one is therefore a claim that "no bound value" means "no change" for it and never
 * "clear it" - which is true of a many-to-one foreign key whose association may legitimately
 * be unmaterialised, and false of an ordinary nullable attribute a caller is entitled to
 * blank. Every use of the parameter must record, at its own site, which behaviour it makes
 * unreachable and why nothing in scope needs it.
 *
 * THE DEFAULT IS EMPTY, SO EVERY EXISTING CALL IS UNCHANGED. The two audit-actor columns
 * remain preserved unconditionally, for every repository, whether or not a second argument is
 * supplied; the parameter only ever ADDS to that floor.
 *
 * @param columnName the column being assigned.
 * @param additionalPreservedColumns further columns this statement must resolve against the
 *   stored value rather than binding a bare placeholder. Supplied by the one adapter whose
 *   entity can legitimately fail to report a column's value; empty for every other caller.
 * @returns the assignment fragment, with its single placeholder.
 */
export function sqlUpdateAssignment(
  columnName: string,
  additionalPreservedColumns: readonly string[] = [],
): string {
  if (AUDIT_ACTOR_COLUMNS.includes(columnName) || additionalPreservedColumns.includes(columnName)) {
    return sqlPreservingUpdateAssignment(columnName);
  }

  return `${columnName} = ?`;
}

/**
 * Render one `SET` assignment that resolves a bound null against the value the row already holds.
 *
 * The same `COALESCE(?, name)` fragment {@link sqlUpdateAssignment} emits for the two audit account
 * columns, published on its own so a repository can apply it to a column of ITS choosing without
 * either restating the literal or widening the shared helper's rule for every table at once.
 *
 * WHY A SECOND ENTRY POINT RATHER THAN A SECOND COLUMN IN {@link AUDIT_ACTOR_COLUMNS}. That list
 * is consulted by NAME for every UPDATE statement in the subtree, so adding a column to it changes
 * every table that happens to carry a column of that name. The audit columns can be treated that way
 * because their rule is genuinely universal - `preUpdate` behaves identically wherever they appear. A
 * MANDATORY FOREIGN KEY is not universal: it is one statement's own invariant, and the statement that
 * owns it is the only place that may declare it.
 *
 * THE ONE CONSUMER, AND THE DEFECT THAT ADDED IT. `MysqlSkuRepository`'s update renders
 * `SwSku.productID` through this helper. A CRITICAL runtime finding had `processProduct_updateSkus`
 * bind that column from a product association its fetch shape never materializes, so an update meant
 * to change two price columns ERASED the parent key of every row it touched - four of five SKUs on the
 * measured product - leaving them unreachable by identity and dropping them out of the product feed.
 * The caller that caused it now names the parent explicitly, and this fragment is the floor beneath
 * that fix: a bound null can no longer erase a stored parent key, whatever a future caller omits.
 *
 * MySQL evaluates the self-reference against the value the row held before the statement, exactly as
 * it does for the audit columns, so no extra round trip and no read-modify-write race is introduced.
 *
 * @param columnName the column being assigned.
 * @returns the assignment fragment, with its single placeholder.
 */
export function sqlPreservingUpdateAssignment(columnName: string): string {
  return `${columnName} = COALESCE(?, ${columnName})`;
}

/**
 * The value an updated row will hold for `modifiedByAccountID` once the statement above has run -
 * the TypeScript mirror of its `COALESCE`.
 *
 * Repositories hand back a fresh entity describing the row they just wrote, and that description
 * has to agree with the row.
 *
 * @param actor the request's audit actor.
 * @param previouslyStored the value the row held before this update.
 * @returns the value the row now holds.
 */
export function resolveStampedModifiedByAccountID(
  actor: AuditActorContext,
  previouslyStored: string | undefined,
): string | undefined {
  return resolveAuditActorAccountID(actor) ?? previouslyStored;
}

/**
 * The narrow execution surface every repository receives.
 *
 * JUDGMENT CALL: constructor injection exists for two reasons that both matter. First, it makes
 * the emitted SQL text and the bound parameter array assertable without A LIVE SERVER.
 *
 * JUDGMENT CALL: there is no `query` method, and there is no way to reach one through this
 * interface.
 */
export interface PreparedStatementExecutor {
  /**
   * Runs a result-set statement and returns its rows.
   *
   * @param sql The statement, owned by the calling repository or by a module under
   * `src/repositories/mysql/sql/`.
   * @param params Values for the positional `?` placeholders, in order.
   * @returns The rows, each keyed by column name with `unknown` values.
   * @throws An error named `SqlParameterError` when any element of `params` is not bindable,
   * raised before the statement is sent.
   */
  execute(sql: string, params?: readonly unknown[]): Promise<readonly SqlRow[]>;

  /**
   * Runs a data-modifying statement and returns what it affected.
   *
   * @param sql An `INSERT`, `UPDATE` or `DELETE` statement.
   * @param params Values for the positional `?` placeholders, in order.
   * @returns The affected-row count and the server warning count.
   * @throws An error named `SqlParameterError` when any element of `params` is not bindable,
   * raised before the statement is sent.
   */
  executeMutation(sql: string, params?: readonly unknown[]): Promise<SqlMutationResult>;

  /**
   * Runs `work` as one all-or-nothing unit against a single connection.
   *
   * This is the replacement for the ambient `cftransaction` the ORM opened around the legacy save
   * and delete cascades.
   *
   * @param work The unit of work.
   * @returns Whatever `work` resolves to, after the commit has succeeded.
   * @throws Whatever `work` throws, after the transaction has been rolled back and the connection
   * released; or whatever the driver raises acquiring the connection.
   */
  transaction<T>(work: (tx: PreparedStatementExecutor) => Promise<T>): Promise<T>;
}

