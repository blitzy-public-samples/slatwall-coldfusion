/**
 * Turns the resolved transport posture into the driver's `ssl` options, or `undefined` when
 * transport is deliberately off.
 *
 * JUDGMENT CALL: `rejectUnauthorized` is a literal `true` in both arms and is never read from
 * configuration.
 *
 * @param tls The resolved posture from `src/lib/config.ts`, already validated, and already refused
 * if it named `disabled` in production or for a non-loopback host.
 * @returns The driver's `ssl` options, or `undefined` for `disabled`.
 */
function buildTlsOptions(tls: DatabaseTlsConfig): SslOptions | undefined {
  if (tls.mode === 'disabled') {
    return undefined;
  }

  const verification: SslOptions = {
    rejectUnauthorized: true,
    verifyIdentity: tls.mode === 'verify-identity',
    minVersion: tls.minimumVersion,
  };

  return tls.certificateAuthority === undefined
    ? verification
    : { ...verification, ca: tls.certificateAuthority };
}

/**
 * Builds the driver options from validated configuration.
 *
 * Every value comes from `src/lib/config.ts`, the owner of the database and runtime keys and the
 * only module this file consults for them - see the ownership split in the module header.
 *
 * Credential on `DatabaseConnectionConfig` is a prototype getter over a private field, so it is
 * not an own enumerable property.
 */
function buildPoolOptions(): PoolOptions {
  const { database, pool, tls } = appConfig.load();
  const ssl = buildTlsOptions(tls);

  const options: PoolOptions = {
    host: database.host,
    port: database.port,
    database: database.database,
    user: database.user,
    password: database.password,
    connectionLimit: pool.connectionLimit,
    connectTimeout: pool.connectTimeout,
    maxIdle: pool.maxIdle,
    idleTimeout: pool.idleTimeout,
    timezone: POOL_TIMEZONE,
  };

  // The key is ADDED only when transport is on, rather than being present with an `undefined`
  // value.
  return ssl === undefined ? options : { ...options, ssl };
}

