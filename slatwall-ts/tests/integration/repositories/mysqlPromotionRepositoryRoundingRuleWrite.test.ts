/**
 * Statement-shape tests for `MysqlPromotionRepository.saveRoundingRule`.
 *
 * ****************************************************************************
 * ** WHY THIS FILE IS NARROW, AND WHY IT EXISTS AT ALL.                     **
 * **                                                                        **
 * ** It covers ONE method. `mysqlPromotionRepository.ts` has no integration  **
 * ** suite of its own - the folder holds one per adapter for the other five,  **
 * ** and the promotion adapter's reads are covered through the engine suites  **
 * ** that consume them. Rather than open a suite for the whole adapter as a   **
 * ** side effect of adding a write, this file is scoped to the write, and     **
 * ** named for it, so its scope is legible from the filename.                **
 * **                                                                        **
 * ** The method it covers is the `super.save(argumentcollection=arguments)`   **
 * ** half of `saveRoundingRule` [model/service/RoundingRuleService.cfc:L63]   **
 * ** that the target had dropped. It needs SQL-level coverage specifically    **
 * ** because there is NO HAND-WRITTEN LEGACY QUERY to diff against: the       **
 * ** statement was generated by Hibernate from the entity's persistent-       **
 * ** property metadata [model/entity/RoundingRule.cfc:L52-L61]. When no       **
 * ** legacy statement exists to compare with, the emitted statement itself    **
 * ** is the only artifact a reviewer can check, so it is pinned here.         **
 * **                                                                        **
 * ** NET-NEW COVERAGE. `meta/tests/unit/dao/` holds only AccountDAOTest and   **
 * ** PaymentDAOTest, and there is no legacy RoundingRuleDAOTest, so nothing    **
 * ** here traces to a legacy antecedent (AAP 0.6.6).                          **
 * ****************************************************************************
 *
 * The four properties worth pinning:
 *
 *   1. INSERT AGAINST UPDATE REPRODUCES HIBERNATE'S DETACHED-ENTITY RECONCILIATION.
 *      A rule with no identifier is inserted under a minted one. A rule that CARRIES
 *      an identifier is probed first, then inserted if no row answers and updated if
 *      one does - because that is what the ORM behind `super.save` did, and trusting
 *      `isNew()` alone would update zero rows and report success.
 *   2. AN UPDATE NEVER REWRITES `createdDateTime`. It is
 *      `hb_populateEnabled="false"` [model/entity/RoundingRule.cfc:L58] and
 *      describes when the row appeared; rewriting it destroys audit history.
 *   3. AN ABSENT COLUMN BINDS `null`, NOT `''`. The columns are nullable
 *      [model/entity/RoundingRule.cfc:L53-L55], and an empty string would later be
 *      handed to `roundValue` as a rounding expression.
 *   4. THE WRITE IS ONE STATEMENT, so it opens no transaction. Wrapping a single
 *      atomic statement would be cargo cult.
 */

import { describe, expect, it } from 'vitest';

import { RoundingRule } from '../../../src/domain/entities/roundingRule.js';
import type { Money } from '../../../src/domain/valueObjects/money.js';
import { MysqlPromotionRepository } from '../../../src/repositories/mysql/mysqlPromotionRepository.js';
import type {
  PreparedStatementExecutor,
  SqlMutationResult,
  SqlRow,
} from '../../../src/repositories/mysql/connection.js';

// ---------------------------------------------------------------------------
// Doubles
